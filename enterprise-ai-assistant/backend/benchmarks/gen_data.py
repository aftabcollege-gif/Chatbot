NAMES = ["فروش", "بازاریابی", "تدارکات", "انبار مرکزی", "حراست", "روابط عمومی",
         "برنامه‌ریزی", "کنترل کیفیت", "امور قراردادها", "خدمات فنی"]
CITIES = ["تهران", "اصفهان", "شیراز", "مشهد", "تبریز", "کرج", "قم", "اهواز"]
DATES = ["فروردین ۱۴۰۳", "خرداد ۱۴۰۳", "مرداد ۱۴۰۳", "مهر ۱۴۰۳", "آذر ۱۴۰۳",
         "بهمن ۱۴۰۳", "فروردین ۱۴۰۴", "تیر ۱۴۰۴", "مهر ۱۴۰۴"]


@dataclass
class SynthDoc:
    title: str
    topic: str
    body: str  # full plain text; chunked by caller


def _fill(template: str, rng: random.Random) -> str:
    return template.format(
        name=rng.choice(NAMES),
        city=rng.choice(CITIES),
        date=rng.choice(DATES),
        num=rng.randint(2, 98),
        code=f"{rng.randint(100, 999)}-{rng.choice('ABCDEF')}",
    )


def generate_doc(rng: random.Random, doc_no: int, sentences: int = 60) -> SynthDoc:
    """Generate one synthetic document (~sentences sentences, ~6 chunks)."""
    topic = rng.choice(list(TOPICS.keys()))
    pool = TOPICS[topic]
    parts = [_fill(rng.choice(pool), rng) for _ in range(sentences)]
    title = f"سند {doc_no} - {topic} - گزارش {rng.choice(DATES)}"
    return SynthDoc(title=title, topic=topic, body="\n".join(parts))


